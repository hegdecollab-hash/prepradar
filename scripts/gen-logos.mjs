// Regenerates lib/company-logos.generated.ts from the simple-icons package (CC0 data).
// Only the icons listed here are bundled; run: node scripts/gen-logos.mjs
import * as si from "simple-icons";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { pathToFileURL } from "node:url";

// Brands removed from current simple-icons: taken from the newest older release that still had them.
// Each entry: [slug, simple-icons version]. Fetched with `npm pack` (needs network when regenerating).
const LEGACY = [
  ["amazon", "14.15.0"],
  ["amazonwebservices", "14.15.0"],
  ["microsoft", "12.4.0"],
  ["adobe", "13.21.0"],
  ["salesforce", "15.22.0"],
  ["oracle", "13.21.0"],
  ["flipkart", "15.22.0"],
  ["linkedin", "13.21.0"],
  ["ibm", "12.4.0"],
  ["walmart", "15.22.0"],
  ["twilio", "15.22.0"],
  ["yahoo", "9.21.0"],
  ["docusign", "12.4.0"],
];

async function loadVersion(ver) {
  const dir = path.join(os.tmpdir(), "simple-icons-legacy", ver);
  const pkg = path.join(dir, "package");
  if (!fs.existsSync(pkg)) {
    fs.mkdirSync(dir, { recursive: true });
    execFileSync("npm", ["pack", `simple-icons@${ver}`, "--silent"], { cwd: dir });
    execFileSync("tar", ["xzf", `simple-icons-${ver}.tgz`], { cwd: dir });
  }
  const entry = ["index.mjs", "index.js"].map((f) => path.join(pkg, f)).find((f) => fs.existsSync(f));
  return import(pathToFileURL(entry).href);
}

const SLUGS =
  "google meta apple uber netflix goldmansachs atlassian airbnb nvidia intel paypal stripe spotify x tesla samsung cisco snapchat doordash shopify zoho swiggy zomato paytm phonepe razorpay visa mastercard github dropbox pinterest reddit lyft bytedance tiktok qualcomm vmware sap intuit ebay expedia coinbase robinhood databricks snowflake palantir infosys tcs wipro accenture".split(
    " ",
  );
const bySlug = new Map(
  Object.values(si)
    .filter((i) => i && i.slug)
    .map((i) => [i.slug, i]),
);
const out = {};
for (const s of SLUGS) {
  const i = bySlug.get(s);
  if (!i) throw new Error(`missing icon ${s}`);
  out[s] = { title: i.title, hex: i.hex, path: i.path, source: "current" };
}
const legacyNotes = [];
for (const [slug, ver] of LEGACY) {
  const mod = await loadVersion(ver);
  const icons = Object.values(mod.default ?? mod).filter((i) => i && typeof i === "object" && "path" in i);
  const i = icons.find((x) => x.slug === slug);
  if (!i) throw new Error(`missing legacy icon ${slug}@${ver}`);
  out[slug] = { title: i.title, hex: i.hex, path: i.path, source: ver };
  legacyNotes.push(`${slug}@${ver}`);
}
const ver = JSON.parse(fs.readFileSync(new URL("../node_modules/simple-icons/package.json", import.meta.url))).version;
fs.writeFileSync(
  new URL("../lib/company-logos.generated.ts", import.meta.url),
  `// GENERATED by scripts/gen-logos.mjs from simple-icons@${ver} (CC0-1.0). Do not edit.\n// Legacy icons (removed from current simple-icons) taken from older releases: ${legacyNotes.join(", ")}.\n// Brand marks belong to their owners; shown for identification only, no endorsement implied.\nexport const LOGOS: Record<string, { title: string; hex: string; path: string; source: string }> = ${JSON.stringify(out)};\n`,
);
console.log(`wrote ${Object.keys(out).length} logos (${legacyNotes.length} legacy)`);
