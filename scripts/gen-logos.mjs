// Regenerates lib/company-logos.generated.ts from the simple-icons package (CC0 data).
// Only the icons listed here are bundled; run: node scripts/gen-logos.mjs
import * as si from "simple-icons";
import fs from "node:fs";

const SLUGS =
  "google meta apple uber netflix goldmansachs atlassian airbnb nvidia intel paypal stripe spotify x tesla samsung cisco snapchat doordash shopify zoho swiggy zomato paytm phonepe razorpay visa mastercard github dropbox pinterest reddit lyft bytedance tiktok qualcomm vmware sap intuit ebay expedia coinbase robinhood databricks snowflake palantir infosys tcs wipro accenture".split(
    " ",
  );
const bySlug = new Map(
  Object.values(si)
    .filter((i) => i && i.slug)
    .map((i) => [i.slug, i]),
);
const out = {};
for (const s of SLUGS) {
  const i = bySlug.get(s);
  if (!i) throw new Error(`missing icon ${s}`);
  out[s] = { title: i.title, hex: i.hex, path: i.path };
}
const ver = JSON.parse(fs.readFileSync(new URL("../node_modules/simple-icons/package.json", import.meta.url))).version;
fs.writeFileSync(
  new URL("../lib/company-logos.generated.ts", import.meta.url),
  `// GENERATED by scripts/gen-logos.mjs from simple-icons@${ver} (CC0-1.0). Do not edit.\n// Brand marks belong to their owners; shown for identification only, no endorsement implied.\nexport const LOGOS: Record<string, { title: string; hex: string; path: string }> = ${JSON.stringify(out)};\n`,
);
console.log(`wrote ${SLUGS.length} logos`);
